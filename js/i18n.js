function cambiarIdioma(idioma) {
    localStorage.setItem('idioma_pref', idioma);
    document.documentElement.lang = idioma;

    const elementos = document.querySelectorAll('[data-i18n]');
    elementos.forEach(el => {
        const clave = el.getAttribute('data-i18n');
        if (traducciones[idioma] && traducciones[idioma][clave]) {
            if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {
                el.placeholder = traducciones[idioma][clave];
            } else {
                el.innerHTML = traducciones[idioma][clave];
            }
        }
    });

    const selectIdioma = document.getElementById('idioma-select');
    if (selectIdioma) {
        selectIdioma.value = idioma;
    }
}

// Al cargar el documento, aplicamos la traducción de forma síncrona antes de mostrar la página
document.addEventListener('DOMContentLoaded', () => {
    const idiomaGuardado = localStorage.getItem('idioma_pref') || 'es';
    cambiarIdioma(idiomaGuardado);

    document.documentElement.classList.remove('traduciendo');
});